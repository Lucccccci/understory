def _tier(energy: int) -> str:
    # 阈值和 Mood.tier 统一（2026-10-19）：40 / 70。
    # 原来这里是 34/67，而 Mood.tier 用 34/67、tone 用 22/34/70 ——
    # 三套阈值在边界上打架，会出现「话里喊累、手边却被安排重活」。
    if energy < 40:
        return "light"
    if energy < 70:
        return "mid"
    return "heavy"


def _thought_tier(valence: int) -> str:
    if valence >= 58:
        return "good"
    if valence >= 38:
        return "plain"
    return "low"


