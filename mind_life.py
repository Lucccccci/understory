def pick_tastes(seed: str, n: int = 3) -> list[str]:
    """挑几样口味。每天固定，不然同一件事的答案会变。"""
    rng = random.Random(f"{seed}|taste")
    flat = [(k, v) for k, items in TASTES.items() for v in items]
    return [f"{k}：{v}" for k, v in rng.sample(flat, min(n, len(flat)))]



def pick_focus(ch, rng_seed: str) -> list[str]:
    """挑出「这次开场要提到的」一两样她自己的状态。

    ## 为什么需要

    她身上有四样东西（手边的事、心里的念头、小麻烦、口味），
    但它们都是**一天一滚**的 —— 一天之内反复生成开场白，
    她就会一直说同一件事（实测：连着重启两次都是「晾衣绳的桩子」）。

    开场白不必全说。这里随机挑 1-2 样返回，其余不出现：

        内容是连贯的    挑出来的那几样确实是当天的状态
        但开场不同      每次挑的组合不一样

    Args:
        ch: Character 实例（读它当天的状态字段）。
        rng_seed: 随机种子。传进程级随机数 —— 同一次运行里
            开场白只生成一次，所以每次调用都该给出不同组合。

    Returns:
        人类可读的短句列表，直接拼进 prompt。可能为空列表
        （那样她就只凭时辰和游戏状态开口，也是一种变化）。
    """
    rng = random.Random(f"{rng_seed}|focus")

    # 每样东西被挑中的权重。
    #
    # 「小麻烦」故意压到最低。它是这四样里**最显眼**的 ——
    # 「晾衣绳那头的桩子松了」这种句子一说出来就占满整个开场。
    # 实测：等权重时它 5 次里出现 4 次，开场白基本被它垄断。
    #
    # 它该是**偶尔提起**的东西，不是每次见面第一句。
    pool: list[tuple[str, float]] = []
    if getattr(ch, "today_task", ""):
        pool.append((f"你手边正在做的事：{ch.today_task}", 1.0))
    if getattr(ch, "today_thought", ""):
        pool.append((f"你心里正想着：{ch.today_thought}", 1.0))
    tastes = getattr(ch, "today_tastes", []) or []
    if tastes:
        pool.append(("你这两天口味上偏着：" + "、".join(tastes[:2]), 0.8))
    if getattr(ch, "today_trouble", ""):
        pool.append((f"你这边有件小麻烦：{ch.today_trouble}", 0.5))

    if not pool:
        return []

    # 多数时候挑两样，偶尔一样 —— 一样的时候开场更利落
    texts = [t for t, _ in pool]
    weights = [w for _, w in pool]
    k = 2 if (len(pool) >= 2 and rng.random() < 0.65) else 1

    picked = rng.choices(texts, weights=weights, k=k)
    seen: list[str] = []          # choices 是有放回的，去重
    for x in picked:
        if x not in seen:
            seen.append(x)
    return seen


def trouble_block(trouble: str, tastes: list[str],
                  observations: list[str]) -> str:
    """拼成给模型看的一段。"""
    lines = ["## 你自己的日子（这些是你自己的，可以主动拿出来说）", ""]

    if trouble:
        lines.append(f"- 眼下有件小麻烦：{trouble}")
        lines.append("  它不大，但一直搁着。他要是问起或能帮上，你会说；"
                     "**不说也无妨，别每句都提。**")
    if tastes:
        lines.append("- 你的口味（这些是稳定的，不要每回说得不一样）：")
        for t in tastes:
            lines.append(f"    · {t}")

    # 观察（「你眼里的他」）2026-11-08 从这里搬走了 ——
    # 它和"我的日子"不是一类东西，混在一段里读起来串味。
    # 现在由 mind_brain 单独出一段「近来你看见的他」，带日期和证据。

    lines.append("")
    lines.append("这些东西**可以主动说** —— 你的日子是你自己的谈资，"
                 "不必等他问「你在忙什么」。但每轮至多说一样。")
    return "\n".join(lines)
