# 她对他的「观察」上限。
#
# 原值 6 —— 而实测她早就攒满 6 条了，于是 `observe()` 里的
# `if len(existing) >= MAX: return None` 让这个功能**永远停住**。
# 用户的原话：「『她眼里的我』部分已经好几天没更新了」。
#
# 12 条足够描述一个人的主要脾性，又不至于变成流水账。
# 满 12 条之后**淘汰最旧的**（见 Character.add_observation），
# 而不是拒绝新增 —— 人的认识本来会变。
MAX_OBSERVATIONS = 20


def _norm(s: str) -> str:
    return re.sub(r"\s+", "", s or "")


def observe(text: str, existing: list[str]) -> str | None:
    """从一句话里看出「他是怎样的人」。看出新的就返回那条观察。

    ## 判据

    记的是**行为模式**（「他累了不吭声」），不是**信息**（「他妹妹叫小满」）。
    信息归记忆系统管，这里只管「她认识了一个什么样的人」。
    """
    t = _norm(text)
    if len(t) < 4:
        return None
    for pat, obs in _OBS_PATTERNS:
        if re.search(pat, t):
            if any(_norm(obs) == _norm(x) for x in existing):
                return None
            # ⚠️ 满了**不再返回 None** —— 交给 `Character.add_observation`
            # 淘汰最旧的。原来的 `return None` 让功能在满 6 条那天彻底死掉。
            # 人的认识会变，新的该能顶掉旧的。
            return obs
    return None


